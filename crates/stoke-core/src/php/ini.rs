//! php.ini per PHP version: a generated part Stoke owns plus the user's `user.ini`, appended.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::php::manifest::{compare_versions, ExtensionSource, Os};
use crate::{atomic, CoreError, StokePaths};

/// Extensions every Windows build ships as DLLs and Laravel apps expect (macOS builds compile them in).
const WINDOWS_EXTENSIONS: &[&str] = &[
    "bz2",
    "curl",
    "exif",
    "fileinfo",
    "gd",
    "gmp",
    "intl",
    "mbstring",
    "mysqli",
    "openssl",
    "pdo_mysql",
    "pdo_pgsql",
    "pdo_sqlite",
    "pgsql",
    "sockets",
    "sodium",
    "sqlite3",
    "xsl",
    "zip",
];

pub struct IniContext {
    pub os: Os,
    pub minor: String,
    pub install_dir: PathBuf,
    pub cacert: PathBuf,
    /// The optional extensions that are switched on, with where they come from.
    pub extensions_on: Vec<(String, ExtensionSource)>,
    /// Stoke's dump script, loaded before every PHP run; `None` when dumps are off.
    pub prepend: Option<PathBuf>,
    /// SPX's web key and report folder, written when spx is switched on.
    pub spx: Option<(String, PathBuf)>,
}

fn quoted(path: &Path) -> String {
    format!("\"{}\"", path.display())
}

/// The generated part of php.ini.
pub fn render_ini(ctx: &IniContext) -> String {
    let mut ini =
        String::from("; Generated by Stoke. Changes here are overwritten: put your own settings in user.ini.\n\n");
    let _ = writeln!(ini, "memory_limit = 512M");
    // As in PHP's own php.ini files: no $_ENV. `artisan serve` blanks every $_ENV key it does not pass
    // on, PHPRC too, and its server then ran without this php.ini.
    let _ = writeln!(ini, "variables_order = \"GPCS\"");
    let _ = writeln!(ini, "upload_max_filesize = 128M");
    let _ = writeln!(ini, "post_max_size = 128M");
    let _ = writeln!(ini, "max_execution_time = 300");
    let _ = writeln!(ini, "date.timezone = UTC");
    let _ = writeln!(ini, "curl.cainfo = {}", quoted(&ctx.cacert));
    let _ = writeln!(ini, "openssl.cafile = {}", quoted(&ctx.cacert));
    ini.push('\n');
    if ctx.os == Os::Windows {
        let _ = writeln!(ini, "extension_dir = {}", quoted(&ctx.install_dir.join("ext")));
        for ext in WINDOWS_EXTENSIONS {
            let _ = writeln!(ini, "extension={ext}");
        }
        // From PHP 8.5 opcache is always built in; loading it again only prints a warning.
        if compare_versions(&ctx.minor, "8.5").is_lt() {
            let _ = writeln!(ini, "zend_extension=opcache");
        }
        ini.push('\n');
    }
    for (name, source) in &ctx.extensions_on {
        match source {
            ExtensionSource::Builtin => continue,
            ExtensionSource::Dll { .. } => {
                let _ = writeln!(ini, "extension={name}");
            }
            ExtensionSource::ZendDll { .. } => {
                let _ = writeln!(ini, "zend_extension={name}");
            }
            ExtensionSource::ZendSo { file } => {
                // macOS archives: always a "/" path, also when rendered elsewhere (tests on Windows).
                let _ = writeln!(ini, "zend_extension=\"{}/{}\"", ctx.install_dir.display(), file);
            }
            ExtensionSource::So { file } => {
                let _ = writeln!(ini, "extension=\"{}/{}\"", ctx.install_dir.display(), file);
            }
        }
        if let ("spx", Some((key, dir))) = (name.as_str(), &ctx.spx) {
            // Profiles start only for requests that carry the key, and only from this machine.
            let _ = writeln!(ini, "spx.http_enabled = 1");
            let _ = writeln!(ini, "spx.http_key = \"{key}\"");
            // Caddy listens on both loopback addresses; SPX compares them as text.
            let _ = writeln!(ini, "spx.http_ip_whitelist = \"127.0.0.1,::1\"");
            let _ = writeln!(ini, "spx.data_dir = {}", quoted(dir));
            // SPX's report pages ship in the archive (its built-in path is the build machine's).
            let _ = writeln!(ini, "spx.http_ui_assets_dir = \"{}/share/spx/web-ui\"", ctx.install_dir.display());
        }
        if name == "xdebug" {
            // Debugging starts only when a request asks for it (browser extension, XDEBUG_TRIGGER).
            let _ = writeln!(ini, "xdebug.mode = debug,develop");
            let _ = writeln!(ini, "xdebug.start_with_request = trigger");
        }
    }
    if let Some(prepend) = &ctx.prepend {
        let _ = writeln!(ini, "\nauto_prepend_file = {}", quoted(prepend));
    }
    ini.push_str("\n; user.ini is appended below by Stoke\n");
    ini
}

pub fn ini_dir(paths: &StokePaths, minor: &str) -> PathBuf {
    paths.config.join("php").join(minor)
}

/// Writes php.ini = `generated` + the user's user.ini (created with a short note on first use).
pub fn write_ini(paths: &StokePaths, minor: &str, generated: &str) -> Result<(), CoreError> {
    let dir = ini_dir(paths, minor);
    std::fs::create_dir_all(&dir).map_err(|e| CoreError::io(&dir, e))?;
    let user_path = dir.join("user.ini");
    if !user_path.exists() {
        let note = format!("; Your own settings for PHP {minor}. Stoke appends this file to php.ini.\n");
        atomic::write(&user_path, note.as_bytes())?;
    }
    let user = std::fs::read_to_string(&user_path).map_err(|e| CoreError::io(&user_path, e))?;
    atomic::write(&dir.join("php.ini"), format!("{generated}{user}").as_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn redis() -> (String, ExtensionSource) {
        let src = ExtensionSource::Dll {
            version: "6.3.0".into(),
            url: "u".into(),
            sha256: "s".into(),
            file: "php_redis.dll".into(),
        };
        ("redis".into(), src)
    }

    fn xdebug_win() -> (String, ExtensionSource) {
        let src = ExtensionSource::ZendDll {
            version: "3.5.3".into(),
            url: "u".into(),
            sha256: "s".into(),
            file: "php_xdebug.dll".into(),
        };
        ("xdebug".into(), src)
    }

    fn windows(minor: &str, on: Vec<(String, ExtensionSource)>) -> String {
        render_ini(&IniContext {
            os: Os::Windows,
            minor: minor.into(),
            install_dir: Path::new(r"C:\Users\Jörg Müller\.config\stoke\data\php\versions\8.4").into(),
            cacert: Path::new(r"C:\Users\Jörg Müller\.config\stoke\data\php\cacert.pem").into(),
            extensions_on: on,
            prepend: None,
            spx: None,
        })
    }

    #[test]
    fn the_prepend_line_is_written_when_dumps_are_on() {
        let off = windows("8.4", vec![]);
        assert!(!off.contains("auto_prepend_file"), "{off}");
        let on = render_ini(&IniContext {
            os: Os::Macos,
            minor: "8.4".into(),
            install_dir: "/h/php/8.4".into(),
            cacert: "/h/cacert.pem".into(),
            extensions_on: vec![],
            prepend: Some("/h/data/collector/prepend.php".into()),
            spx: None,
        });
        assert!(on.contains("\nauto_prepend_file = \"/h/data/collector/prepend.php\"\n"), "{on}");
        assert!(
            on.find("auto_prepend_file").unwrap() < on.find("; user.ini is appended").unwrap(),
            "a prepend file in user.ini comes later and wins"
        );
    }

    #[test]
    fn windows_ini_loads_redis_but_not_a_switched_off_xdebug() {
        let ini = windows("8.4", vec![redis()]);
        assert!(ini.contains("\nextension=redis\n"), "{ini}");
        assert!(!ini.contains("xdebug"), "{ini}");
        assert!(ini.contains("\nextension=mbstring\n"), "{ini}");
        assert!(ini.contains("\nzend_extension=opcache\n"), "{ini}");
        assert!(ini.contains("\nmemory_limit = 512M\n"), "{ini}");
    }

    /// `artisan serve` blanks every `$_ENV` key it does not pass through, PHPRC too, so its server
    /// ran without Stoke's php.ini (no extensions). With `$_ENV` empty, as in PHP's own php.ini
    /// files, the server inherits PHPRC.
    #[test]
    fn env_variables_stay_out_of_dollar_env() {
        let ini = windows("8.4", vec![]);
        assert!(ini.contains("\nvariables_order = \"GPCS\"\n"), "{ini}");
    }

    #[test]
    fn xdebug_on_adds_its_settings() {
        let ini = windows("8.4", vec![redis(), xdebug_win()]);
        assert!(
            ini.contains("\nzend_extension=xdebug\nxdebug.mode = debug,develop\nxdebug.start_with_request = trigger\n"),
            "{ini}"
        );
    }

    // Path::join only writes Windows separators on Windows, where this ini is rendered.
    #[cfg(windows)]
    #[test]
    fn paths_are_quoted_and_keep_non_ascii_names() {
        let ini = windows("8.4", vec![]);
        assert!(
            ini.contains(r#"extension_dir = "C:\Users\Jörg Müller\.config\stoke\data\php\versions\8.4\ext""#),
            "{ini}"
        );
        assert!(ini.contains(r#"curl.cainfo = "C:\Users\Jörg Müller\.config\stoke\data\php\cacert.pem""#), "{ini}");
    }

    #[test]
    fn php_8_5_on_windows_does_not_load_the_built_in_opcache_again() {
        assert!(!windows("8.5", vec![]).contains("zend_extension=opcache"));
    }

    #[test]
    fn macos_loads_xdebug_from_the_archive_and_nothing_else() {
        let ini = render_ini(&IniContext {
            os: Os::Macos,
            minor: "8.4".into(),
            install_dir: "/Users/j/.config/stoke/data/php/versions/8.4".into(),
            cacert: "/Users/j/.config/stoke/data/php/cacert.pem".into(),
            extensions_on: vec![
                ("redis".into(), ExtensionSource::Builtin),
                ("xdebug".into(), ExtensionSource::ZendSo { file: "lib/xdebug.so".into() }),
            ],
            prepend: None,
            spx: None,
        });
        assert!(
            ini.contains("\nzend_extension=\"/Users/j/.config/stoke/data/php/versions/8.4/lib/xdebug.so\"\n"),
            "{ini}"
        );
        assert!(!ini.contains("extension_dir"), "{ini}");
        assert!(!ini.contains("extension=redis"), "{ini}");
        assert!(!ini.contains("extension=mbstring"), "{ini}");
    }

    #[test]
    fn macos_loads_spx_with_stokes_key_and_folder() {
        let source: ExtensionSource = serde_json::from_str(r#"{"kind":"so","file":"lib/spx.so"}"#).unwrap();
        assert_eq!(source, ExtensionSource::So { file: "lib/spx.so".into() });
        let ctx = |on: Vec<(String, ExtensionSource)>| IniContext {
            os: Os::Macos,
            minor: "8.4".into(),
            install_dir: "/Users/j/stoke/php/8.4".into(),
            cacert: "/Users/j/stoke/cacert.pem".into(),
            extensions_on: on,
            prepend: None,
            spx: Some(("k123".into(), "/Users/j/stoke/data/spx".into())),
        };
        let ini = render_ini(&ctx(vec![("spx".into(), source)]));
        assert!(ini.contains("\nextension=\"/Users/j/stoke/php/8.4/lib/spx.so\"\n"), "{ini}");
        assert!(ini.contains("\nspx.http_enabled = 1\n"), "{ini}");
        assert!(ini.contains("\nspx.http_key = \"k123\"\n"), "{ini}");
        assert!(ini.contains("\nspx.http_ip_whitelist = \"127.0.0.1,::1\"\n"), "{ini}");
        assert!(ini.contains("\nspx.http_ui_assets_dir = \"/Users/j/stoke/php/8.4/share/spx/web-ui\"\n"), "{ini}");
        assert!(ini.contains("\nspx.data_dir = \"/Users/j/stoke/data/spx\"\n"), "{ini}");
        assert!(!render_ini(&ctx(vec![])).contains("spx."), "spx off: no settings");
    }

    #[test]
    fn user_ini_is_appended_and_created_once() {
        let d = tempfile::tempdir().unwrap();
        let p = StokePaths::at(d.path());
        p.ensure().unwrap();
        write_ini(&p, "8.4", "generated\n").unwrap();
        let dir = p.config.join("php").join("8.4");
        assert!(std::fs::read_to_string(dir.join("user.ini")).unwrap().starts_with("; Your own settings"));
        std::fs::write(dir.join("user.ini"), "memory_limit = 1G\n").unwrap();
        write_ini(&p, "8.4", "generated\n").unwrap();
        assert_eq!(std::fs::read_to_string(dir.join("php.ini")).unwrap(), "generated\nmemory_limit = 1G\n");
    }
}
