//! php.ini per PHP version: a generated part Hearth owns plus the user's `user.ini`, appended.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::php::manifest::{compare_versions, ExtensionSource, Os};
use crate::{atomic, CoreError, HearthPaths};

/// Extensions every Windows build ships as DLLs and Laravel apps expect (macOS builds compile them in).
const WINDOWS_EXTENSIONS: &[&str] = &[
    "bz2",
    "curl",
    "exif",
    "fileinfo",
    "gd",
    "gmp",
    "intl",
    "mbstring",
    "mysqli",
    "openssl",
    "pdo_mysql",
    "pdo_pgsql",
    "pdo_sqlite",
    "pgsql",
    "sockets",
    "sodium",
    "sqlite3",
    "xsl",
    "zip",
];

pub struct IniContext {
    pub os: Os,
    pub minor: String,
    pub install_dir: PathBuf,
    pub cacert: PathBuf,
    /// The optional extensions that are switched on, with where they come from.
    pub extensions_on: Vec<(String, ExtensionSource)>,
}

fn quoted(path: &Path) -> String {
    format!("\"{}\"", path.display())
}

/// The generated part of php.ini.
pub fn render_ini(ctx: &IniContext) -> String {
    let mut ini =
        String::from("; Generated by Hearth. Changes here are overwritten: put your own settings in user.ini.\n\n");
    let _ = writeln!(ini, "memory_limit = 512M");
    let _ = writeln!(ini, "upload_max_filesize = 128M");
    let _ = writeln!(ini, "post_max_size = 128M");
    let _ = writeln!(ini, "max_execution_time = 300");
    let _ = writeln!(ini, "date.timezone = UTC");
    let _ = writeln!(ini, "curl.cainfo = {}", quoted(&ctx.cacert));
    let _ = writeln!(ini, "openssl.cafile = {}", quoted(&ctx.cacert));
    ini.push('\n');
    if ctx.os == Os::Windows {
        let _ = writeln!(ini, "extension_dir = {}", quoted(&ctx.install_dir.join("ext")));
        for ext in WINDOWS_EXTENSIONS {
            let _ = writeln!(ini, "extension={ext}");
        }
        // From PHP 8.5 opcache is always built in; loading it again only prints a warning.
        if compare_versions(&ctx.minor, "8.5").is_lt() {
            let _ = writeln!(ini, "zend_extension=opcache");
        }
        ini.push('\n');
    }
    for (name, source) in &ctx.extensions_on {
        match source {
            ExtensionSource::Builtin => continue,
            ExtensionSource::Dll { .. } => {
                let _ = writeln!(ini, "extension={name}");
            }
            ExtensionSource::ZendDll { .. } => {
                let _ = writeln!(ini, "zend_extension={name}");
            }
            ExtensionSource::ZendSo { file } => {
                // macOS archives: always a "/" path, also when rendered elsewhere (tests on Windows).
                let _ = writeln!(ini, "zend_extension=\"{}/{}\"", ctx.install_dir.display(), file);
            }
        }
        if name == "xdebug" {
            // Debugging starts only when a request asks for it (browser extension, XDEBUG_TRIGGER).
            let _ = writeln!(ini, "xdebug.mode = debug,develop");
            let _ = writeln!(ini, "xdebug.start_with_request = trigger");
        }
    }
    ini.push_str("\n; user.ini is appended below by Hearth\n");
    ini
}

pub fn ini_dir(paths: &HearthPaths, minor: &str) -> PathBuf {
    paths.config.join("php").join(minor)
}

/// Writes php.ini = `generated` + the user's user.ini (created with a short note on first use).
pub fn write_ini(paths: &HearthPaths, minor: &str, generated: &str) -> Result<(), CoreError> {
    let dir = ini_dir(paths, minor);
    std::fs::create_dir_all(&dir).map_err(|e| CoreError::io(&dir, e))?;
    let user_path = dir.join("user.ini");
    if !user_path.exists() {
        let note = format!("; Your own settings for PHP {minor}. Hearth appends this file to php.ini.\n");
        atomic::write(&user_path, note.as_bytes())?;
    }
    let user = std::fs::read_to_string(&user_path).map_err(|e| CoreError::io(&user_path, e))?;
    atomic::write(&dir.join("php.ini"), format!("{generated}{user}").as_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn redis() -> (String, ExtensionSource) {
        let src = ExtensionSource::Dll {
            version: "6.3.0".into(),
            url: "u".into(),
            sha256: "s".into(),
            file: "php_redis.dll".into(),
        };
        ("redis".into(), src)
    }

    fn xdebug_win() -> (String, ExtensionSource) {
        let src = ExtensionSource::ZendDll {
            version: "3.5.3".into(),
            url: "u".into(),
            sha256: "s".into(),
            file: "php_xdebug.dll".into(),
        };
        ("xdebug".into(), src)
    }

    fn windows(minor: &str, on: Vec<(String, ExtensionSource)>) -> String {
        render_ini(&IniContext {
            os: Os::Windows,
            minor: minor.into(),
            install_dir: Path::new(r"C:\Users\Jörg Müller\.config\hearth\data\php\versions\8.4").into(),
            cacert: Path::new(r"C:\Users\Jörg Müller\.config\hearth\data\php\cacert.pem").into(),
            extensions_on: on,
        })
    }

    #[test]
    fn windows_ini_loads_redis_but_not_a_switched_off_xdebug() {
        let ini = windows("8.4", vec![redis()]);
        assert!(ini.contains("\nextension=redis\n"), "{ini}");
        assert!(!ini.contains("xdebug"), "{ini}");
        assert!(ini.contains("\nextension=mbstring\n"), "{ini}");
        assert!(ini.contains("\nzend_extension=opcache\n"), "{ini}");
        assert!(ini.contains("\nmemory_limit = 512M\n"), "{ini}");
    }

    #[test]
    fn xdebug_on_adds_its_settings() {
        let ini = windows("8.4", vec![redis(), xdebug_win()]);
        assert!(
            ini.contains("\nzend_extension=xdebug\nxdebug.mode = debug,develop\nxdebug.start_with_request = trigger\n"),
            "{ini}"
        );
    }

    #[test]
    fn paths_are_quoted_and_keep_non_ascii_names() {
        let ini = windows("8.4", vec![]);
        assert!(
            ini.contains(r#"extension_dir = "C:\Users\Jörg Müller\.config\hearth\data\php\versions\8.4\ext""#),
            "{ini}"
        );
        assert!(ini.contains(r#"curl.cainfo = "C:\Users\Jörg Müller\.config\hearth\data\php\cacert.pem""#), "{ini}");
    }

    #[test]
    fn php_8_5_on_windows_does_not_load_the_built_in_opcache_again() {
        assert!(!windows("8.5", vec![]).contains("zend_extension=opcache"));
    }

    #[test]
    fn macos_loads_xdebug_from_the_archive_and_nothing_else() {
        let ini = render_ini(&IniContext {
            os: Os::Macos,
            minor: "8.4".into(),
            install_dir: "/Users/j/.config/hearth/data/php/versions/8.4".into(),
            cacert: "/Users/j/.config/hearth/data/php/cacert.pem".into(),
            extensions_on: vec![
                ("redis".into(), ExtensionSource::Builtin),
                ("xdebug".into(), ExtensionSource::ZendSo { file: "lib/xdebug.so".into() }),
            ],
        });
        assert!(
            ini.contains("\nzend_extension=\"/Users/j/.config/hearth/data/php/versions/8.4/lib/xdebug.so\"\n"),
            "{ini}"
        );
        assert!(!ini.contains("extension_dir"), "{ini}");
        assert!(!ini.contains("extension=redis"), "{ini}");
        assert!(!ini.contains("extension=mbstring"), "{ini}");
    }

    #[test]
    fn user_ini_is_appended_and_created_once() {
        let d = tempfile::tempdir().unwrap();
        let p = HearthPaths::at(d.path());
        p.ensure().unwrap();
        write_ini(&p, "8.4", "generated\n").unwrap();
        let dir = p.config.join("php").join("8.4");
        assert!(std::fs::read_to_string(dir.join("user.ini")).unwrap().starts_with("; Your own settings"));
        std::fs::write(dir.join("user.ini"), "memory_limit = 1G\n").unwrap();
        write_ini(&p, "8.4", "generated\n").unwrap();
        assert_eq!(std::fs::read_to_string(dir.join("php.ini")).unwrap(), "generated\nmemory_limit = 1G\n");
    }
}
