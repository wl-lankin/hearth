//! PHP FastCGI pools Caddy hands PHP requests to. Windows: several `php-cgi.exe -b` processes per
//! version (one php-cgi handles one request at a time). macOS: one `php-fpm` per version with a
//! generated pool config.

use std::ffi::OsString;
use std::path::PathBuf;

use crate::php::ini::ini_dir;
use crate::php::manifest::Os;
use crate::php::store::install_dir;
use crate::supervisor::ProcessSpec;
use crate::HearthPaths;

/// php-cgi processes per version on Windows.
const WINDOWS_WORKERS: u16 = 4;

/// `19000 + major*100 + minor*10 + i`: 8.4 -> 19840.., well away from Herd's 90xx/91xx.
pub fn pool_ports(os: Os, minor: &str) -> Vec<u16> {
    let mut parts = minor.split('.').map(|p| p.parse::<u16>().unwrap_or(0));
    let (major, minor_n) = (parts.next().unwrap_or(0), parts.next().unwrap_or(0));
    let base = 19000 + major * 100 + minor_n * 10;
    let count = if os == Os::Windows { WINDOWS_WORKERS } else { 1 };
    (base..base + count).collect()
}

fn ini_path(paths: &HearthPaths, minor: &str) -> PathBuf {
    ini_dir(paths, minor).join("php.ini")
}

fn fpm_conf_path(paths: &HearthPaths, minor: &str) -> PathBuf {
    ini_dir(paths, minor).join("php-fpm.conf")
}

fn log_path(paths: &HearthPaths, minor: &str) -> PathBuf {
    paths.logs.join(format!("php-{minor}.log"))
}

pub fn pool_specs(paths: &HearthPaths, os: Os, minor: &str) -> Vec<ProcessSpec> {
    let env = vec![
        ("PHPRC".to_string(), ini_dir(paths, minor).into_os_string()),
        ("PHP_FCGI_MAX_REQUESTS".to_string(), OsString::from("500")),
    ];
    let ini: OsString = ini_path(paths, minor).into_os_string();
    let ports = pool_ports(os, minor);
    match os {
        Os::Windows => ports
            .iter()
            .enumerate()
            .map(|(i, port)| ProcessSpec {
                key: format!("php-{minor}-{i}"),
                program: install_dir(paths, minor).join("php-cgi.exe"),
                args: vec!["-b".into(), format!("127.0.0.1:{port}").into(), "-c".into(), ini.clone()],
                env: env.clone(),
                cwd: None,
                log: log_path(paths, minor),
                ready_port: Some(*port),
            })
            .collect(),
        Os::Macos => vec![ProcessSpec {
            key: format!("php-{minor}"),
            program: install_dir(paths, minor).join("sbin").join("php-fpm"),
            args: vec!["-F".into(), "-y".into(), fpm_conf_path(paths, minor).into_os_string(), "-c".into(), ini],
            env,
            cwd: None,
            log: log_path(paths, minor),
            ready_port: ports.first().copied(),
        }],
    }
}

/// The php-fpm config for one version (macOS).
pub fn render_fpm_conf(paths: &HearthPaths, minor: &str) -> String {
    let port = pool_ports(Os::Macos, minor)[0];
    let fpm_log = paths.logs.join(format!("php-fpm-{minor}.log"));
    let php_log = log_path(paths, minor);
    format!(
        "; Generated by Hearth.\n[global]\nerror_log = \"{}\"\ndaemonize = no\n\n[www]\nlisten = 127.0.0.1:{port}\npm = dynamic\npm.max_children = 8\npm.start_servers = 2\npm.min_spare_servers = 1\npm.max_spare_servers = 3\ncatch_workers_output = yes\nphp_admin_value[error_log] = \"{}\"\n",
        fpm_log.display(),
        php_log.display()
    )
}

/// Writes the php-fpm config for `minor` (macOS only; nothing on Windows).
pub fn write_pool_config(paths: &HearthPaths, minor: &str) -> Result<(), crate::CoreError> {
    if Os::current() == Os::Macos {
        let path = fpm_conf_path(paths, minor);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| crate::CoreError::io(dir, e))?;
        }
        crate::atomic::write(&path, render_fpm_conf(paths, minor).as_bytes())?;
    }
    Ok(())
}

/// The PHP version a site really runs on, and a note when it is not the one it asked for.
pub fn effective_php(
    isolated: Option<&str>,
    installed: &[String],
    default: Option<&str>,
) -> (Option<String>, Option<String>) {
    match (isolated, default) {
        (Some(minor), _) if installed.iter().any(|m| m == minor) => (Some(minor.into()), None),
        (Some(minor), Some(d)) => (Some(d.into()), Some(format!("Uses the default PHP {d} ({minor} was removed)"))),
        (Some(minor), None) => (None, Some(format!("PHP {minor} is not installed"))),
        (None, Some(d)) => (Some(d.into()), None),
        (None, None) => (None, Some("No PHP version is installed".into())),
    }
}
