<script lang="ts">
  import { phpIniGet, phpIniSet } from '../api';

  let { minor, onclose }: { minor: string; onclose: () => void } = $props();

  let generated = $state('');
  let user = $state('');
  let status = $state<string | null>(null);
  let saving = $state(false);

  $effect(() => {
    phpIniGet(minor)
      .then((parts) => {
        generated = parts.generated;
        user = parts.user;
      })
      .catch((e) => (status = String(e)));
  });

  async function save() {
    saving = true;
    try {
      await phpIniSet(minor, user);
      status = 'Saved. New PHP processes use these settings.';
    } catch (e) {
      status = String(e);
    } finally {
      saving = false;
    }
  }
</script>

<div class="editor">
  <div class="head">
    <strong>php.ini for PHP {minor}</strong>
    <button onclick={onclose}>Close</button>
  </div>
  <label for="user-ini-{minor}">Your settings (user.ini)</label>
  <textarea id="user-ini-{minor}" bind:value={user} spellcheck="false" rows="8"></textarea>
  <div class="foot">
    {#if status}<span class="status" aria-live="polite">{status}</span>{/if}
    <button class="primary" onclick={save} disabled={saving}>Save</button>
  </div>
  <details>
    <summary>Generated by Hearth (read only)</summary>
    <pre>{generated}</pre>
  </details>
</div>

